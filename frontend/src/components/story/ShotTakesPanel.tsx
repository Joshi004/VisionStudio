const STATUS: Record<
  ShotTakesEntry["status"],
  { label: string; color: string }
> = {
  not_generated: { label: "Not generated", color: "gray" },
  generated: { label: "Generated", color: "green" },
  out_of_date: { label: "Out of date", color: "yellow" },
  failed: { label: "Failed checks", color: "red" },
  unchecked: { label: "Not checked", color: "orange" },
};

/** A shot is generated by a press when it has no good clip and is not waiting for a check. */
function needsClip(shot: ShotTakesEntry): boolean {
  return (
    shot.can_run && shot.status !== "generated" && shot.status !== "unchecked"
  );
}

/** The technical check of a take, as a badge. */
function CheckBadge({ take }: { take: ShotTake }) {
  if (take.validation === null) {
    return take.state === "ready" ? (
      <Badge variant="light" color="orange">
        Not checked
      </Badge>
    ) : null;
  }
  if (take.validation.passed) {
    return (
      <Badge variant="light" color="green">
        Check passed
      </Badge>
    );
  }
  return take.validation.accepted ? (
    <Badge variant="light" color="orange">
      Check failed, used anyway
    </Badge>
  ) : (
    <Badge variant="light" color="red">
      Check failed
    </Badge>
  );
}

/**
 * The dialogue check of a take whose shot carries dialogue, as a badge: what the speech in the
 * clip matched against the lines. Nothing for a shot with no dialogue or a clip that has not
 * passed its technical check (it is not transcribed then).
 */
function DialogueBadge({ take }: { take: ShotTake }) {
  if (
    take.dialogue.length === 0 ||
    take.state === "generating" ||
    take.state === "failed" ||
    !take.validation?.passed
  ) {
    return null;
  }
  const check = take.dialogue_check;
  if (check === null) {
    return take.state === "checking_dialogue" ? (
      <Badge variant="light" color="blue">
        Checking dialogue
      </Badge>
    ) : (
      <Badge variant="light" color="orange">
        Dialogue not checked
      </Badge>
    );
  }
  if (check.passed) {
    return (
      <Badge variant="light" color="green">
        Dialogue matched ({check.similarity}%)
      </Badge>
    );
  }
  return check.accepted ? (
    <Badge variant="light" color="orange">
      Dialogue {check.similarity}%, used anyway
    </Badge>
  ) : (
    <Badge variant="light" color="red">
      Dialogue did not match ({check.similarity}%)
    </Badge>
  );
}

/** The clip failed its technical check, or its dialogue did not match. */
function failedACheck(take: ShotTake): boolean {
  return (
    take.validation?.passed === false || take.dialogue_check?.passed === false
  );
}

/**
 * A take may be selected once its checks are done, also one that failed a check: the user may
 * use it anyway. A clip that passed its technical check still needs its dialogue checked.
 */
function canSelect(take: ShotTake): boolean {
  if (take.state !== "ready" || take.selected || take.validation === null) {
    return false;
  }
  const dialoguePending =
    take.validation.passed &&
    take.dialogue.length > 0 &&
    take.dialogue_check === null;
  return !dialoguePending;
}

const TAKE_STATE: Record<ShotTake["state"], { label: string; color: string }> =
  {
    generating: { label: "Generating", color: "blue" },
    checking_dialogue: { label: "Checking dialogue", color: "blue" },
    ready: { label: "Ready", color: "green" },
    failed: { label: "Failed", color: "red" },
  };

/** "2.33 s, 56 frames, 1344x768, with sound". */
function clipText(take: ShotTake): string {
  const parts: string[] = [];
  if (take.duration_s !== null) {
    parts.push(`${take.duration_s.toFixed(2)} s`);
  }
  if (take.frame_count !== null) {
    parts.push(`${take.frame_count} frames`);
  }
  if (take.width !== null && take.height !== null) {
    parts.push(`${take.width}x${take.height}`);
  }
  if (take.has_audio !== null) {
    parts.push(take.has_audio ? "with sound" : "no sound");
  }
  return parts.join(", ");
}

type TakeRowProps = {
  take: ShotTake;
  busy: boolean;
  onSelect: () => void;
};

/** One take: its number, state, what the clip measured, and a button to select it. */
function TakeRow({ take, busy, onSelect }: TakeRowProps) {
  const state = TAKE_STATE[take.state];
  return (
    <Stack gap={2}>
      <Group gap="xs" wrap="nowrap">
        <Badge variant="outline" color="gray">
          Take {take.take_number}
        </Badge>
        <Badge variant="light" color={state.color}>
          {state.label}
        </Badge>
        <CheckBadge take={take} />
        <DialogueBadge take={take} />
        {take.selected && (
          <Badge variant="light" color="teal">
            Selected
          </Badge>
        )}
        <Text size="xs" c="dimmed" style={{ flexGrow: 1 }}>
          seed {take.seed}
          {take.retry_attempt > 0
            ? `, automatic retry ${take.retry_attempt}`
            : ""}
          {take.state === "ready" || take.state === "checking_dialogue"
            ? `, ${clipText(take)}`
            : ""}
        </Text>
        {take.job !== null && take.job.status !== "succeeded" && (
          <JobStatusBadge job={take.job} />
        )}
        {take.dialogue_job !== null &&
          take.dialogue_job.status !== "succeeded" && (
            <JobStatusBadge job={take.dialogue_job} />
          )}
        {canSelect(take) &&
          (failedACheck(take) ? (
            <Button
              size="compact-xs"
              variant="light"
              color="orange"
              disabled={busy}
              onClick={onSelect}
              title="Use this clip although it failed a check. The shot's automatic retries stop."
            >
              Use anyway
            </Button>
          ) : (
            <Button
              size="compact-xs"
              variant="default"
              disabled={busy}
              onClick={onSelect}
            >
              Select
            </Button>
          ))}
      </Group>
      {take.dialogue.length > 0 && take.dialogue_check !== null && (
        <Stack gap={0} ml={8}>
          {take.dialogue.map((line) => (
            <Text key={line.unit_id} size="xs" c="dimmed">
              {line.label || line.unit_id}: &ldquo;{line.text}&rdquo;
            </Text>
          ))}
          <Text
            size="xs"
            c={take.dialogue_check.passed ? "dimmed" : "red"}
            style={{ wordBreak: "break-word" }}
          >
            Heard:{" "}
            {take.dialogue_check.heard_text
              ? `\u201C${take.dialogue_check.heard_text}\u201D`
              : "nothing"}{" "}
            (needed {take.dialogue_check.threshold}%)
          </Text>
        </Stack>
      )}
      {take.anchor != null && (
        <Text size="xs" c="dimmed" ml={8}>
          Continues shot {take.anchor.from_shot_id}: starts from{" "}
          {take.anchor.frame_index !== null
            ? `frame ${take.anchor.frame_index}`
            : "the last frame"}{" "}
          of its take {take.anchor.take_number}
          {take.anchor.use === "reference" ? " (as a reference picture)" : ""}.
        </Text>
      )}
      {take.reasons.map((text) => (
        <Text key={text} size="xs" c="yellow.8">
          {text}
        </Text>
      ))}
      {take.validation?.passed === false &&
        take.validation.problems.map((problem) => (
          <Text key={problem.code} size="xs" c="red">
            {problem.message}
          </Text>
        ))}
      {take.state === "failed" && take.job?.error && (
        <Text size="xs" c="red">
          {take.job.error}
        </Text>
      )}
    </Stack>
  );
}

type ShotRowProps = {
  entry: ShotTakesEntry;
  maxRetries: number;
  busy: boolean;
  onGenerate: () => void;
  onSelect: (takeId: number) => void;
};

/** What the newest take's failed check says, and where the automatic retries stand. */
function failureLines(
  entry: ShotTakesEntry,
  maxRetries: number,
): { text: string; key: string }[] {
  const newest = entry.takes[0];
  if (entry.status !== "failed" || !newest || !newest.validation) {
    return [];
  }
  // The technical check failed, or, when it passed, the dialogue check did.
  const failed = !newest.validation.passed
    ? newest.validation
    : newest.dialogue_check?.passed === false
      ? newest.dialogue_check
      : null;
  if (failed === null) {
    return [];
  }
  const lines = failed.problems.map((problem) => ({
    text: problem.message,
    key: problem.code,
  }));
  if (newest.validation.kind === "plan") {
    lines.push({
      text: "Another take cannot fix this. Plan this scene's shots again.",
      key: "plan",
    });
  } else if (newest.retry_attempt >= maxRetries) {
    lines.push({
      text:
        maxRetries === 0
          ? "Automatic retries are off. Press Regenerate to try again."
          : `Retries used up (${newest.retry_attempt} of ${maxRetries}). Press Regenerate to try again.`,
      key: "retries",
    });
  }
  if (entry.takes.some(canSelect)) {
    lines.push({
      text: "To use a clip as it is, show the takes and press Use anyway.",
      key: "use-anyway",
    });
  }
  return lines;
}

/** One shot: its status, the selected clip, and its takes. */
function ShotRow({
  entry,
  maxRetries,
  busy,
  onGenerate,
  onSelect,
}: ShotRowProps) {
  const [open, setOpen] = useState(false);
  const { shot, takes, job } = entry;
  const status = STATUS[entry.status];
  const selected = takes.find((take) => take.selected) ?? null;
  const hasTakes = takes.length > 0;
  const generating = takes.some((take) => take.state === "generating");
  const failed = entry.status === "failed";
  const newest = takes[0];
  const retrying =
    newest !== undefined &&
    newest.state === "generating" &&
    newest.retry_attempt > 0;
  const heard = selected?.dialogue_check ?? null;

  return (
    <Stack
      gap={4}
      style={
        failed
          ? {
              borderLeft: "3px solid var(--mantine-color-red-6)",
              paddingLeft: 8,
            }
          : undefined
      }
    >
      <Group align="flex-start" wrap="nowrap" gap="sm">
        <Badge
          variant="outline"
          color="gray"
          miw={64}
          style={{ flexShrink: 0, textTransform: "none" }}
        >
          {shot.id}
        </Badge>
        <Stack gap={2} style={{ flexGrow: 1 }}>
          <Group gap="xs">
            <Badge variant="light" color={status.color}>
              {status.label}
            </Badge>
            <Badge
              variant="light"
              color="gray"
              title="How long the shot lasts on the timeline"
            >
              {shot.duration_seconds} s target
            </Badge>
            {entry.continues_from != null && (
              <Badge
                variant="light"
                color="indigo"
                style={{ textTransform: "none" }}
                title="No cut: this shot starts from the last frame of the shot before it"
              >
                Continues {entry.continues_from}
              </Badge>
            )}
            {hasTakes && (
              <Badge variant="light" color="gray">
                {takes.length} {takes.length === 1 ? "take" : "takes"}
              </Badge>
            )}
            {job && job.status !== "succeeded" && <JobStatusBadge job={job} />}
            <Text size="sm" style={{ wordBreak: "break-word" }}>
              {shot.description}
            </Text>
          </Group>
          {!entry.can_run && entry.blocked_reason !== null && (
            <Text size="xs" c="dimmed">
              {entry.blocked_reason}
            </Text>
          )}
          {entry.reasons.map((text) => (
            <Text key={text} size="xs" c="yellow.8">
              {text}
            </Text>
          ))}
          {failureLines(entry, maxRetries).map((line) => (
            <Text key={line.key} size="xs" c="red">
              {line.text}
            </Text>
          ))}
          {retrying && (
            <Text size="xs" c="blue">
              The last clip failed a check. Generating it again automatically
              (retry {newest.retry_attempt} of {maxRetries}). Selecting a take
              stops the retries.
            </Text>
          )}
          {takes.some((take) => take.state === "checking_dialogue") && (
            <Text size="xs" c="blue">
              Listening to the clip and comparing the speech with the
              shot&apos;s dialogue.
            </Text>
          )}
          {entry.status === "unchecked" && (
            <Text size="xs" c="orange">
              A clip of this shot has not been fully checked (its technical
              check, or its speech against the dialogue). Press Check takes to
              check it.
            </Text>
          )}
          {job?.status === "failed" && !generating && !failed && (
            <Alert color="red" p="xs" title="The last generation failed">
              {job.error ?? "The job failed."}
            </Alert>
          )}
        </Stack>
        <Group gap="xs" wrap="nowrap" style={{ flexShrink: 0 }}>
          {hasTakes && (
            <Button
              size="compact-xs"
              variant="default"
              onClick={() => setOpen((value) => !value)}
            >
              {open ? "Hide the takes" : "Show the takes"}
            </Button>
          )}
          <Button
            size="compact-xs"
            variant="default"
            disabled={!entry.can_run || busy}
            onClick={onGenerate}
          >
            {hasTakes ? "Regenerate" : "Generate"}
          </Button>
        </Group>
      </Group>
      {selected !== null && selected.url !== null && (
        <Stack gap={2} ml={72}>
          <video
            key={selected.id}
            src={selected.url}
            controls
            preload="metadata"
            style={{ maxWidth: 420, width: "100%" }}
          />
          <Text size="xs" c="dimmed">
            Take {selected.take_number}: {clipText(selected)}. The shot lasts{" "}
            {shot.duration_seconds} s; the clip is trimmed to that when the
            video is put together.
            {heard !== null &&
              (heard.passed
                ? ` Its speech matched the dialogue by ${heard.similarity}%.`
                : ` Its speech matched the dialogue by only ${heard.similarity}%; you chose to use it anyway.`)}
            {selected.validation?.passed === false &&
              " It failed its technical check; you chose to use it anyway."}
          </Text>
        </Stack>
      )}
      {hasTakes && (
        <Collapse expanded={open}>
          <Stack gap="xs" pt={4} ml={72}>
            {takes.map((take) => (
              <TakeRow
                key={take.id}
                take={take}
                busy={busy}
                onSelect={() => onSelect(take.id)}
              />
            ))}
          </Stack>
        </Collapse>
      )}
    </Stack>
  );
}

type SceneRowProps = {
  scene: SceneShotTakes;
  maxRetries: number;
  busy: boolean;
  onGenerateScene: () => void;
  onGenerateShot: (shotId: string) => void;
  onSelect: (shotId: string, takeId: number) => void;
};

/** One scene: how many of its shots have a clip, and its shots. */
function SceneRow({
  scene,
  maxRetries,
  busy,
  onGenerateScene,
  onGenerateShot,
  onSelect,
}: SceneRowProps) {
  const generated = scene.shots.filter(
    (shot) => shot.status === "generated",
  ).length;
  const outOfDate = scene.shots.filter(
    (shot) => shot.status === "out_of_date",
  ).length;
  // What "Generate scene" would do for this scene.
  const todo = scene.shots.filter(needsClip).length;
  const failedCount = scene.shots.filter(
    (shot) => shot.status === "failed",
  ).length;

  return (
    <Stack gap={6}>
      <Group align="flex-start" wrap="nowrap" gap="sm">
        <Badge
          variant="outline"
          color="gray"
          miw={40}
          style={{ flexShrink: 0, textTransform: "none" }}
        >
          {scene.index}
        </Badge>
        <Group gap="xs" style={{ flexGrow: 1 }}>
          <Text size="sm" fw={500}>
            {scene.title}
          </Text>
          <Badge variant="light" color="gray">
            {generated} of {scene.shots.length} generated
          </Badge>
          {outOfDate > 0 && (
            <Badge variant="light" color="yellow">
              {outOfDate} out of date
            </Badge>
          )}
          {failedCount > 0 && (
            <Badge variant="light" color="red">
              {failedCount} failed checks
            </Badge>
          )}
        </Group>
        <Button
          size="compact-sm"
          variant="default"
          disabled={busy || todo === 0}
          onClick={onGenerateScene}
          style={{ flexShrink: 0 }}
        >
          Generate scene
        </Button>
      </Group>
      {scene.shots.length > 0 && (
        <Stack gap="sm" ml={48}>
          {scene.shots.map((entry) => (
            <ShotRow
              key={entry.shot.id}
              entry={entry}
              maxRetries={maxRetries}
              busy={busy}
              onGenerate={() => onGenerateShot(entry.shot.id)}
              onSelect={(takeId) => onSelect(entry.shot.id, takeId)}
            />
          ))}
        </Stack>
      )}
    </Stack>
  );
}

/**
 * The shot generation stage: each shot's compiled prompt, pictures and dialogue audio are sent to
 * the video model, and the clip is stored as a take of the shot. Every press makes one more
 * take; the take that finished (or was selected) last is the selected one. Nothing starts by
 * itself: a clip holds 4 to 8 GPUs for minutes. Each clip is checked in code when it is stored;
 * one that failed is generated again by the server with another seed, up to the limit in
 * Settings (PHASE-029). A clip of a shot with dialogue is then transcribed, and its speech must
 * match the lines closely enough (a setting) to be selected by itself; one that does not is
 * generated again the same way (PHASE-031). The user may still use a clip that failed either
 * check, and selecting a take stops the shot's automatic retries.
 */
export function ShotTakesPanel({ projectId }: ShotTakesPanelProps) {
  const { data, isLoading, isError, error } = useShotTakes(projectId);
  const generateAll = useGenerateAllShots(projectId);
  const generateScene = useGenerateSceneShots(projectId);
  const generateOne = useGenerateOneShot(projectId);
  const selectTake = useSelectTake(projectId);
  const checkTakes = useCheckShotTakes(projectId);

  const entries = data?.entries ?? [];
  const busy =
    generateAll.isPending ||
    generateScene.isPending ||
    generateOne.isPending ||
    selectTake.isPending ||
    checkTakes.isPending;
  const projectBlocked = (data?.blocked_reason ?? null) !== null;
  const unchecked = data?.unchecked_count ?? 0;
  const checkJob = data?.check_job ?? null;
  const checking = isJobActive(checkJob);
  const maxRetries = data?.max_retries ?? 0;
  // What "Generate all" would do: the shots that may be generated and have no good clip.
  const allCount = entries.reduce(
    (sum, scene) => sum + scene.shots.filter(needsClip).length,
    0,
  );
  // The shots the last press could not do, with why.
  const skipped = [
    ...(generateAll.data?.skipped ?? []),
    ...(generateScene.data?.skipped ?? []),
  ].filter(
    (item) => item.shot_id !== null && !item.reason.startsWith("Already"),
  );

  return (
    <Paper withBorder p="md" radius="md">
      <Stack gap="sm">
        <Group justify="space-between" align="flex-start">
          <Stack gap={2}>
            <Title order={4}>Shot generation</Title>
            <Text size="sm" c="dimmed">
              Sends each shot&apos;s prompt, pictures and dialogue speech to the
              video model and keeps the clip as a take of the shot. Shots run
              side by side when the GPU server has room. Each press adds a take,
              and the take that finished or was selected last is the one used.
              Each clip gets a technical check (it decodes, has sound, and has
              the size and number of frames asked for), and for a shot with
              dialogue the speech in the clip is transcribed and must match the
              lines. A clip that fails either check is generated again by itself
              with another seed, up to the limit in Settings. You can still use
              a clip that failed with Use anyway; selecting a take stops the
              shot&apos;s automatic retries. Nothing else starts by itself.
            </Text>
          </Stack>
          <Group gap="xs" wrap="nowrap" style={{ flexShrink: 0 }}>
            {unchecked > 0 && (
              <Button
                variant="default"
                onClick={() => checkTakes.mutate()}
                loading={checkTakes.isPending || checking}
                disabled={isLoading || isError || busy}
                title="Checks the clips that have not been fully checked (technical check, and for dialogue the speech). It starts no clip generation."
              >
                Check takes ({unchecked} not checked)
              </Button>
            )}
            <Button
              onClick={() => generateAll.mutate()}
              loading={generateAll.isPending}
              disabled={
                isLoading || isError || busy || projectBlocked || allCount === 0
              }
            >
              Generate all
            </Button>
          </Group>
        </Group>
        {checkJob?.status === "failed" && (
          <Alert color="red" title="The check of the clips failed">
            {checkJob.error ?? "The job failed."}
          </Alert>
        )}

        {isLoading && <Loader size="sm" />}
        {isError && (
          <Alert color="red" title="Could not load the shot clips">
            {describeError(error)}
          </Alert>
        )}
        {[generateAll, generateScene, generateOne, selectTake, checkTakes].map(
          (mutation, position) =>
            mutation.isError && (
              <Alert
                key={position}
                color="red"
                title="Could not generate the clips"
              >
                {describeError(mutation.error)}
              </Alert>
            ),
        )}
        {skipped.length > 0 && (
          <Alert color="blue" title="Not generated">
            <Stack gap={2}>
              {skipped.map((item) => (
                <Text key={`${item.scene_id}/${item.shot_id}`} size="sm">
                  {item.title}, {item.shot_id}: {item.reason}
                </Text>
              ))}
            </Stack>
          </Alert>
        )}
        {data && data.blocked_reason !== null && (
          <Text size="sm" c="dimmed">
            {data.blocked_reason}
          </Text>
        )}
        {entries.length > 0 && <Divider />}

        {entries.map((scene) => (
          <SceneRow
            key={scene.id}
            scene={scene}
            maxRetries={maxRetries}
            busy={busy}
            onGenerateScene={() => generateScene.mutate(scene.id)}
            onGenerateShot={(shotId) =>
              generateOne.mutate({ sceneId: scene.id, shotId })
            }
            onSelect={(shotId, takeId) =>
              selectTake.mutate({ sceneId: scene.id, shotId, takeId })
            }
          />
        ))}
      </Stack>
    </Paper>
  );
}
