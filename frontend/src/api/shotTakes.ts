import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import type { QueryClient } from "@tanstack/react-query";

import { api } from "./client";
import { ApiError, detailMessage } from "./errors";
import { invalidateAfterJobAction } from "./jobs";
import { ACTIVE_POLL_MS, isJobActive } from "./polling";
import { isValidProjectId } from "./projects";
import type { components } from "./schema";
import { shotPromptsKey } from "./shotPrompts";

export type ShotTakes = components["schemas"]["ShotTakesOut"];
export type SceneShotTakes = components["schemas"]["SceneShotTakesOut"];
export type ShotTakesEntry = components["schemas"]["ShotTakesEntryOut"];
export type ShotTake = components["schemas"]["ShotTakeOut"];
export type ShotTakesRun = components["schemas"]["ShotTakesRunManyOut"];

/**
 * The shot-take query of a project. It starts with the shot prompts' key (and so the generation
 * requests', the shot references' and the shot definitions'), so whatever refreshes those
 * (compiling a prompt, planning a request, saving the story) refreshes this too: a clip is
 * generated from its shot's prompt.
 */
export function shotTakesKey(projectId: number) {
  return [...shotPromptsKey(projectId), "takes"] as const;
}

async function fetchShotTakes(projectId: number) {
  const { data, error, response } = await api.GET(
    "/api/projects/{project_id}/shot-takes",
    { params: { path: { project_id: projectId } } },
  );
  if (!data) {
    throw new ApiError(
      detailMessage(
        error,
        `Could not load the shot clips (HTTP ${response.status}).`,
      ),
      response.status,
    );
  }
  return data;
}

/**
 * Where each shot's generation stands. Nothing is generated by itself (a failed clip is retried
 * by the server), so the page asks again only while a generation, check or dialogue-check job
 * is waiting or running (a clip takes minutes).
 */
export function useShotTakes(projectId: number) {
  return useQuery({
    queryKey: shotTakesKey(projectId),
    queryFn: () => fetchShotTakes(projectId),
    enabled: isValidProjectId(projectId),
    refetchInterval: (current) =>
      isJobActive(current.state.data?.check_job) ||
      current.state.data?.entries.some((scene) =>
        scene.shots.some(
          (shot) =>
            isJobActive(shot.job) ||
            shot.takes.some((take) => isJobActive(take.dialogue_job)),
        ),
      )
        ? ACTIVE_POLL_MS
        : false,
  });
}

/** A refusal can mean something changed, so the jobs are loaded again as well. */
function refreshAfterRun(queryClient: QueryClient, projectId: number) {
  return Promise.all([
    queryClient.invalidateQueries({ queryKey: shotTakesKey(projectId) }),
    invalidateAfterJobAction(queryClient),
  ]);
}

function startError(error: unknown, status: number): ApiError {
  return new ApiError(
    detailMessage(error, `Could not start the shot clip (HTTP ${status}).`),
    status,
  );
}

/** "Generate all": starts a job for every shot that has a current prompt and no current clip. */
export function useGenerateAllShots(projectId: number) {
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async () => {
      const { data, error, response } = await api.POST(
        "/api/projects/{project_id}/shot-takes/run",
        { params: { path: { project_id: projectId } } },
      );
      if (!data) {
        throw startError(error, response.status);
      }
      return data;
    },
    onSettled: () => refreshAfterRun(queryClient, projectId),
  });
}

/** Starts the jobs that generate every shot of one scene that has no current clip. */
export function useGenerateSceneShots(projectId: number) {
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async (sceneId: string) => {
      const { data, error, response } = await api.POST(
        "/api/projects/{project_id}/shot-takes/{scene_id}/run",
        { params: { path: { project_id: projectId, scene_id: sceneId } } },
      );
      if (!data) {
        throw startError(error, response.status);
      }
      return data;
    },
    onSettled: () => refreshAfterRun(queryClient, projectId),
  });
}

/** Starts the job that makes one more take of one shot (Generate or Regenerate). */
export function useGenerateOneShot(projectId: number) {
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async (target: { sceneId: string; shotId: string }) => {
      const { data, error, response } = await api.POST(
        "/api/projects/{project_id}/shot-takes/{scene_id}/{shot_id}/run",
        {
          params: {
            path: {
              project_id: projectId,
              scene_id: target.sceneId,
              shot_id: target.shotId,
            },
          },
        },
      );
      if (!data) {
        throw startError(error, response.status);
      }
      return data;
    },
    onSettled: () => refreshAfterRun(queryClient, projectId),
  });
}

/** Makes a ready take the selected one of its shot. */
export function useSelectTake(projectId: number) {
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async (target: {
      sceneId: string;
      shotId: string;
      takeId: number;
    }) => {
      const { data, error, response } = await api.POST(
        "/api/projects/{project_id}/shot-takes/{scene_id}/{shot_id}/takes/{take_id}/select",
        {
          params: {
            path: {
              project_id: projectId,
              scene_id: target.sceneId,
              shot_id: target.shotId,
              take_id: target.takeId,
            },
          },
        },
      );
      if (!data) {
        throw new ApiError(
          detailMessage(
            error,
            `Could not select the take (HTTP ${response.status}).`,
          ),
          response.status,
        );
      }
      return data;
    },
    onSettled: () =>
      queryClient.invalidateQueries({ queryKey: shotTakesKey(projectId) }),
  });
}

/**
 * "Check takes": starts the local job that checks the clips made before the checks existed. It
 * starts no generation, so it costs seconds and no GPU time.
 */
export function useCheckShotTakes(projectId: number) {
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async () => {
      const { data, error, response } = await api.POST(
        "/api/projects/{project_id}/shot-takes/check",
        { params: { path: { project_id: projectId } } },
      );
      if (!data) {
        throw new ApiError(
          detailMessage(
            error,
            `Could not start the check of the clips (HTTP ${response.status}).`,
          ),
          response.status,
        );
      }
      return data;
    },
    onSettled: () => refreshAfterRun(queryClient, projectId),
  });
}
